#ifndef PLAYERBOTS_FLAG96_H
#define PLAYERBOTS_FLAG96_H

#include "Define.h"

// AC's 96-bit flag wrapper, dropped from TC master. The ported module's spell
// family mask code still speaks this type (SpellInfo::SpellFamilyFlags on AC);
// sources include this header directly or reach it through the module PCH.
class flag96
{
private:
    uint32 part[3];

public:
    flag96(uint32 p1 = 0, uint32 p2 = 0, uint32 p3 = 0)
    {
        part[0] = p1;
        part[1] = p2;
        part[2] = p3;
    }

    [[nodiscard]] bool IsEqual(uint32 p1 = 0, uint32 p2 = 0, uint32 p3 = 0) const
    {
        return (part[0] == p1 && part[1] == p2 && part[2] == p3);
    }

    [[nodiscard]] bool HasFlag(uint32 p1 = 0, uint32 p2 = 0, uint32 p3 = 0) const
    {
        return (part[0] & p1 || part[1] & p2 || part[2] & p3);
    }

    void Set(uint32 p1 = 0, uint32 p2 = 0, uint32 p3 = 0)
    {
        part[0] = p1;
        part[1] = p2;
        part[2] = p3;
    }

    bool operator<(flag96 const& right) const
    {
        for (uint8 i = 3; i > 0; --i)
        {
            if (part[i - 1] < right.part[i - 1])
                return true;
            if (part[i - 1] > right.part[i - 1])
                return false;
        }
        return false;
    }

    bool operator==(flag96 const& right) const
    {
        return part[0] == right.part[0] && part[1] == right.part[1] && part[2] == right.part[2];
    }

    bool operator!=(flag96 const& right) const { return !(*this == right); }

    flag96& operator=(flag96 const& right)
    {
        part[0] = right.part[0];
        part[1] = right.part[1];
        part[2] = right.part[2];
        return *this;
    }
    flag96(flag96 const&) = default;
    flag96(flag96&&) = default;

    flag96 operator&(flag96 const& right) const
    {
        return flag96(part[0] & right.part[0], part[1] & right.part[1], part[2] & right.part[2]);
    }

    flag96& operator&=(flag96 const& right)
    {
        part[0] &= right.part[0];
        part[1] &= right.part[1];
        part[2] &= right.part[2];
        return *this;
    }

    flag96 operator|(flag96 const& right) const
    {
        return flag96(part[0] | right.part[0], part[1] | right.part[1], part[2] | right.part[2]);
    }

    flag96& operator|=(flag96 const& right)
    {
        part[0] |= right.part[0];
        part[1] |= right.part[1];
        part[2] |= right.part[2];
        return *this;
    }

    flag96 operator~() const { return flag96(~part[0], ~part[1], ~part[2]); }

    flag96 operator^(flag96 const& right) const
    {
        return flag96(part[0] ^ right.part[0], part[1] ^ right.part[1], part[2] ^ right.part[2]);
    }

    flag96& operator^=(flag96 const& right)
    {
        part[0] ^= right.part[0];
        part[1] ^= right.part[1];
        part[2] ^= right.part[2];
        return *this;
    }

    operator bool() const { return (part[0] != 0 || part[1] != 0 || part[2] != 0); }

    [[nodiscard]] uint32 operator[](uint8 i) const { return part[i]; }
};

#endif
